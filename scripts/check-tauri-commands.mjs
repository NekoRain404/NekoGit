#!/usr/bin/env node
/// Verifies every Tauri command registered in `generate_handler!` has an ACL permission
/// and a matching capability entry, preventing silently denied frontend invokes.
import { readFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';

const repoRoot = resolve(import.meta.dirname, '..');
const libPath = resolve(repoRoot, 'src-tauri/src/lib.rs');
const capabilityPath = resolve(repoRoot, 'src-tauri/capabilities/default.json');
const permissionsDirs = [
  resolve(repoRoot, 'src-tauri/permissions/autogenerated/commands'),
  resolve(repoRoot, 'src-tauri/permissions/autogenerated'),
];

const lib = readFileSync(libPath, 'utf8');
const handlerMatch = lib.match(/generate_handler!\[([\s\S]*?)\]/);
if (!handlerMatch) {
  console.error('Could not find tauri::generate_handler! in src-tauri/src/lib.rs');
  process.exit(1);
}

const commands = handlerMatch[1]
  .split(',')
  .map((entry) => entry.trim())
  .filter((entry) => entry.startsWith('desktop_'));
const capability = JSON.parse(readFileSync(capabilityPath, 'utf8'));
const permissions = new Set(capability.permissions ?? []);

const missing = [];
for (const command of commands) {
  const permission = `allow-${command.replaceAll('_', '-')}`;
  const permissionFile = permissionsDirs
    .map((dir) => resolve(dir, `${command}.toml`))
    .find((path) => existsSync(path));
  if (!permissions.has(permission))
    missing.push(`${command}: missing capability entry ${permission}`);
  if (!permissionFile) {
    missing.push(`${command}: missing permission file in ${permissionsDirs.join(' or ')}`);
  }
}

if (missing.length > 0) {
  console.error('Tauri command permission check failed:');
  for (const entry of missing) console.error(`  - ${entry}`);
  process.exit(1);
}

console.log(
  `Checked ${commands.length} Tauri commands: capabilities and permission files are complete.`
);
